#!/usr/bin/env python3
"""
Build data/qiraat-data.js from rules/*.json and the Tanzil Uthmani text.

    python3 tools/build_data.py            # build every rules file
    python3 tools/build_data.py 2          # build one surah's output only
    python3 tools/build_data.py --review   # also print every pattern match for checking

Rule file format (rules/002-baqarah.json):

{
  "surah": 2,                        # the surah whose farsh this file covers (an-Nashr order)
  "complete": true,                  # the surah's own farsh is fully entered
  "source": "...",
  "rules": [
    {
      "id": "yukhadiun",
      "ref": "النشر ٢/٢٠٧",
      "at":   [{"s": 2, "a": 9, "w": "^يخدعون$", "n": 2}],     # explicit places; n = nth match in the ayah
      "find": {"w": "...", "in": "all" | [surahs], "except": [[s, a], [s, a, nth]], "expect": 15},
      "h": "{w} {next}",              # optional display text; default is the mushaf word
      "v": [["{w}", "*"], ["يُخَٰدِعُونَ", "nafi kathir abuamr", "optional note"]],
      "ok": false                     # true once checked against the source
    }
  ]
}

Word conditions (in "at" entries and "find"):
  w        regex over the bare rasm (harakat/marks stripped, ٱأإآ→ا, ى→ي)
  fw       regex over the word with harakat (shadda-before-vowel order, as in Tanzil)
  prev     rasm regex on the previous word
  next     rasm regex on the next word (the next ayah's first word at an ayah end)
  next_fw  harakat regex on the next word

Variant text placeholders: {w} mushaf word, {w:damm} with its last kasra made damma, {w:sin} with its first ص made س, {next} next word.
Reader specs accept rawi codes, qari ids and group names (see GROUPS); "*" = the rest;
prefix "~" = بخلف عنه; suffix "!" = the wajh taken under رواية الإثبات.

Occurrences generated by any rule file are written to the output of the surah they occur in.
"""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RULES_DIR = ROOT / "rules"
DATA_DIR = ROOT / "data"
QURAN = ROOT / "sources" / "quran-uthmani.txt"

QURRA = {
    "nafi": ["qa", "wr"], "kathir": ["bz", "qn"], "abuamr": ["da", "su"], "ibnamir": ["hi", "dh"],
    "asim": ["sh", "hf"], "hamzah": ["kh", "kd"], "kisai": ["ah", "dk"], "abujafar": ["iw", "ij"],
    "yaqub": ["rw", "rh"], "khalaf": ["is", "id"],
}
CODES = [c for pair in QURRA.values() for c in pair]
GROUPS = {
    **QURRA,
    # an-Nashr collective terms
    "madaniyan": QURRA["nafi"] + QURRA["abujafar"],                         # المدنيان
    "basriyan": QURRA["abuamr"] + QURRA["yaqub"],                           # البصريان
    "kufiyun": QURRA["asim"] + QURRA["hamzah"] + QURRA["kisai"] + QURRA["khalaf"],  # الكوفيون
    "akhawan": QURRA["hamzah"] + QURRA["kisai"],                            # الأخوان
    "harmiyan": QURRA["nafi"] + QURRA["kathir"],                            # الحرميان
}

SURAH_SLUGS = {}  # filled from existing data file names when present


def rasm(word):
    """Strip harakat and Quranic marks so rules can be written against the bare rasm."""
    w = re.sub(r"[ؐ-ًؚ-ٰٟۖ-ۭ࣓-ࣿـ]", "", word)
    w = re.sub(r"[ٱأإآ]", "ا", w)
    return w.replace("ى", "ي").replace("ی", "ي")


class Ayah(list):
    """Words of one ayah; .after holds the first word of the next ayah (wasl across the ayah end)."""
    after = None


def load_quran():
    ayat = {}
    for line in QURAN.read_text(encoding="utf8").splitlines():
        m = re.match(r"(\d+)\|(\d+)\|(.*)", line)
        if not m:
            continue
        s, a, text = int(m.group(1)), int(m.group(2)), m.group(3)
        if a == 1 and s not in (1, 9):
            text = re.sub(r"^بِسْمِ ٱللَّهِ ٱلرَّحْمَـٰنِ ٱلرَّحِيمِ ", "", text)
        words = [w for w in text.split() if rasm(w)]
        ayat[(s, a)] = Ayah((w, rasm(w)) for w in words)
    for (s, a), words in ayat.items():
        nxt = ayat.get((s, a + 1))
        words.after = nxt[0] if nxt else None
    return ayat


def damm_last(word):
    """Replace the last kasra of the word with a damma (the كسر/ضم of the first of two sakins)."""
    i = word.rfind("\u0650")
    return word if i < 0 else word[:i] + "\u064f" + word[i + 1:]


def next_word(words, i):
    return words[i + 1] if i + 1 < len(words) else getattr(words, "after", None)


def expand_spec(spec, where):
    out = []
    for tok in spec.split():
        if tok == "*":
            out.append(tok)
            continue
        m = re.fullmatch(r"(~?)([a-z]+)(!?)", tok)
        if not m:
            raise ValueError(f"{where}: bad reader token {tok!r}")
        pre, name, suf = m.groups()
        if name in CODES:
            codes = [name]
        elif name in GROUPS:
            codes = GROUPS[name]
        else:
            raise ValueError(f"{where}: unknown reader {name!r}")
        out += [f"{pre}{c}{suf}" for c in codes]
    return " ".join(dict.fromkeys(out))


def nfd(s):
    # put shadda before its vowel (the Tanzil order) so harakat regexes match however they were typed
    return re.sub("([\u064b-\u0650\u0652])\u0651", "\u0651\\1", s)


def word_matches(cond, words, i):
    """cond keys: w (rasm regex), fw (regex on the word with harakat), prev/next (rasm regex on the
    neighbouring word), next_fw (regex on the next word with harakat)."""
    word, r = words[i]
    if "w" in cond and not re.search(cond["w"], r):
        return False
    if "fw" in cond and not re.search(nfd(cond["fw"]), nfd(word)):
        return False
    if "prev" in cond and not (i > 0 and re.search(cond["prev"], words[i - 1][1])):
        return False
    nxt = next_word(words, i)
    if "next" in cond and not (nxt and re.search(cond["next"], nxt[1])):
        return False
    if "next_fw" in cond and not (nxt and re.search(nfd(cond["next_fw"]), nfd(nxt[0]))):
        return False
    return True


def occurrences(rule, ayat, where):
    found = []
    for loc in rule.get("at", []):
        words = ayat.get((loc["s"], loc["a"]))
        if words is None:
            raise ValueError(f"{where}: no ayah {loc['s']}:{loc['a']}")
        hits = [i for i in range(len(words)) if word_matches(loc, words, i)]
        if not hits:
            raise ValueError(f"{where}: {loc.get('w') or loc.get('fw')!r} not found in {loc['s']}:{loc['a']} — {' '.join(r for _, r in words)}")
        if "n" in loc:
            if loc["n"] > len(hits):
                raise ValueError(f"{where}: only {len(hits)} match(es) in {loc['s']}:{loc['a']}")
            hits = [hits[loc["n"] - 1]]
        found += [(loc["s"], loc["a"], i, "at") for i in hits]
    if "find" in rule:
        f = rule["find"]
        scope = f.get("in", "all")
        except_ = {tuple(e) for e in f.get("except", [])}
        for (s, a), words in ayat.items():
            if scope != "all" and s not in scope:
                continue
            if (s, a) in except_:
                continue
            nth = 0
            for i in range(len(words)):
                if word_matches(f, words, i):
                    nth += 1
                    if (s, a, nth) in except_:
                        continue
                    found.append((s, a, i, "find"))
        if "expect" in f and len(found) != f["expect"]:
            raise ValueError(f"{where}: expected {f['expect']} matches, found {len(found)}")
    return sorted(set(found))


def build(only_surah=None, review=False):
    ayat = load_quran()
    out = defaultdict(list)
    placed = {}  # (s, a, word index) -> (kind, where, item)
    sources = {}
    complete = set()
    problems = 0
    for path in sorted(RULES_DIR.glob("*.json")):
        doc = json.loads(path.read_text(encoding="utf8"))
        sources[doc["surah"]] = doc.get("source", "")
        if doc.get("complete"):
            complete.add(doc["surah"])
        for rule in doc["rules"]:
            where = f"{path.name}#{rule.get('id', '?')}"
            try:
                occ = occurrences(rule, ayat, where)
                variants = [[t, expand_spec(spec, where), *rest] for t, spec, *rest in rule["v"]]
            except ValueError as e:
                print("ERROR", e, file=sys.stderr)
                problems += 1
                continue
            if review and "find" in rule:
                print(f"\n# {where}  ({len(occ)} matches)")
                for s, a, i, _ in occ:
                    print(f"  {s}:{a}  {ayat[(s, a)][i][0]}")
            for s, a, i, kind in occ:
                words = ayat[(s, a)]
                word = words[i][0]
                nxt = (next_word(words, i) or ("", ""))[0]
                fill = lambda t: (t.replace("{w:damm}", damm_last(word)).replace("{w:sin}", word.replace("ص", "س", 1))
                                   .replace("{w}", word).replace("{next}", nxt))
                item = {
                    "a": a,
                    "h": fill(rule.get("h", "{w}")),
                    "v": [[fill(t), spec, *rest] for t, spec, *rest in variants],
                    "_pos": i,
                }
                if rule.get("ref"):
                    item["ref"] = rule["ref"]
                if rule.get("ok"):
                    item["ok"] = True
                key = (s, a, i)
                if key in placed:
                    prev_kind, prev_where, prev_item = placed[key]
                    if prev_kind == kind:
                        print(f"WARN {where} and {prev_where} both cover {s}:{a} {word}", file=sys.stderr)
                    elif kind == "at":       # a specific statement beats a general rule
                        out[s].remove(prev_item)
                    else:
                        continue
                placed[key] = (kind, where, item)
                out[s].append(item)

    DATA_DIR.mkdir(exist_ok=True)
    blocks = []
    for s, items in sorted(out.items()):
        if only_surah and s != only_surah:
            continue
        items.sort(key=lambda it: (it["a"], it["_pos"]))
        for it in items:
            del it["_pos"]
        lines = ",\n".join("    " + json.dumps(it, ensure_ascii=False) for it in items)
        blocks.append(
            "QIRAAT_SURAHS.push({\n"
            f"  surah: {s},\n"
            f"  complete: {'true' if s in complete else 'false'},\n"
            f"  source: {json.dumps(sources.get(s) or 'النشر في القراءات العشر لابن الجزري', ensure_ascii=False)},\n"
            "  items: [\n" + lines + "\n  ]\n});\n"
        )
        print(f"surah {s}: {len(items)} positions{' (complete)' if s in complete else ''}")
    js = (
        "/* Generated by tools/build_data.py from rules/*.json — do not edit by hand.\n"
        " * Mushaf words are taken verbatim from:\n"
        " *   Tanzil Quran Text (Uthmani, Version 1.1)\n"
        " *   Copyright (C) 2007-2026 Tanzil Project\n"
        " *   License: Creative Commons Attribution 3.0\n"
        " *   Permission is granted to copy and distribute verbatim copies of this text, but CHANGING IT IS NOT ALLOWED.\n"
        " *   Source: Tanzil Project — https://tanzil.net (check updates at http://tanzil.net/updates/) */\n"
        "var QIRAAT_SURAHS = window.QIRAAT_SURAHS = window.QIRAAT_SURAHS || [];\n" + "".join(blocks)
    )
    (DATA_DIR / "qiraat-data.js").write_text(js, encoding="utf8")
    print(f"{sum(len(v) for v in out.values())} positions -> data/qiraat-data.js")
    return problems


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    sys.exit(1 if build(int(args[0]) if args else None, "--review" in sys.argv) else 0)
